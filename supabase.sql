-- 在 Supabase Dashboard > SQL Editor 執行
create table if not exists public.rhythm_scores (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  score integer not null default 0,
  accuracy numeric(5,2) not null default 0,
  max_combo integer not null default 0,
  song text not null default '',
  difficulty text not null default '',
  created_at timestamptz not null default now()
);
alter table public.rhythm_scores enable row level security;
drop policy if exists "Users can read their own scores" on public.rhythm_scores;
create policy "Users can read their own scores" on public.rhythm_scores
for select to authenticated using (auth.uid() = user_id);
drop policy if exists "Users can insert their own scores" on public.rhythm_scores;
create policy "Users can insert their own scores" on public.rhythm_scores
for insert to authenticated with check (auth.uid() = user_id);
grant select, insert on public.rhythm_scores to authenticated;
grant usage, select on sequence public.rhythm_scores_id_seq to authenticated;
